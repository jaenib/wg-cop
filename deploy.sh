#!/usr/bin/env bash
# =============================================================================
# mario_robotta / wg-cop — server reference for agents and humans
# =============================================================================
#
# PRIMARY DEPLOY METHOD: GitHub Actions (100% automated)
#   Trigger : push to `main` branch
#   Workflow : .github/workflows/deploy.yml
#   What it does:
#     test → ssh → checkout tested commit → offline checks → restart → health check
#   A merge/push to main is a production release, not a routine local save.
#   Do NOT scp code, do NOT git push to the server manually.
#
# EMERGENCY FALLBACK (GitHub Actions broken):
#   Use the parent deploy.sh, two directories above this file:
#     ../../deploy.sh mario_robotta
#   Review its rsync exclusions before use: the live store is wg_data_alpha.json
#   in the bot dir (plus *.bak archives); it, .secrets/ and venv/ must stay excluded.
#   Git remote alias for this repo on your Mac: jaenib-wgcop
#
# =============================================================================
# SERVER
# =============================================================================
#   Host        : 82.165.45.100
#   User        : root
#   SSH         : ssh root@82.165.45.100
#   Bot dir     : /usr/bots/wg_cop/
#   Service     : wg_cop   (systemctl)
#   Venv        : /usr/bots/wg_cop/venv/
#
# Files NOT in git (stay on server):
#   config.py            — bot token + Telegram IDs (secrets)
#   wg_data_alpha.json   — legacy expense/chore/penalty database
#   wg_data_alpha.json   — versioned multi-home store after migration
#
# =============================================================================
# UTILITY COMMANDS
# =============================================================================

set -euo pipefail
umask 077

SERVER="root@82.165.45.100"

case "${1:-help}" in

  status)
    ssh "$SERVER" 'systemctl status wg_cop --no-pager && journalctl -u wg_cop -n 40 --no-pager'
    ;;

  logs)
    ssh "$SERVER" 'journalctl -u wg_cop -f'
    ;;

  restart)
    echo "Restarting wg_cop …"
    ssh "$SERVER" 'systemctl restart wg_cop && systemctl status wg_cop --no-pager'
    ;;

  data)
    # A private, unique destination avoids replacing an earlier recovery copy.
    # The envelope is atomically replaced by the bot, so it is one snapshot.
    snapshot=$(mktemp "${TMPDIR:-/tmp}/wg-cop-state.XXXXXX")
    if ssh "$SERVER" 'cd /usr/bots/wg_cop && tar -czf - wg_data_alpha.json' > "$snapshot"; then
      echo "Private state snapshot saved to $snapshot (gzip tar archive)."
    else
      rm -f "$snapshot"
      exit 1
    fi
    ;;

  push-data)
    # Whole-store emergency restore. Never overwrite while the bot is running.
    # Usage: ./deploy.sh push-data /path/to/wg_data_alpha.json
    LOCAL="${2:?usage: deploy.sh push-data <file.json>}"
    script_dir=$(cd -- "$(dirname -- "$0")" && pwd)
    python3 "$script_dir/ops/validate_state.py" "$LOCAL"
    staging=$(ssh "$SERVER" 'umask 077; mktemp /usr/bots/wg_cop/.restore.XXXXXXXX')
    # Only accept the path generated by the fixed remote mktemp template.
    if [[ ! "$staging" =~ ^/usr/bots/wg_cop/\.restore\.[a-zA-Z0-9]+$ ]]; then
      echo "Unexpected remote staging path; refusing upload" >&2
      exit 1
    fi
    scp "$LOCAL" "$SERVER:$staging"
    ssh "$SERVER" bash -s -- "$staging" <<'REMOTE'
set -euo pipefail
umask 077
staging=$1
cd /usr/bots/wg_cop
trap 'rm -f "$staging"' EXIT
python3 ops/validate_state.py "$staging" --same-format-as wg_data_alpha.json
systemctl stop wg_cop
promoted=0
restore_exit() {
    status=$?
    if [ "$status" -ne 0 ] && [ "$promoted" -eq 0 ]; then
        systemctl start wg_cop
    fi
    rm -f "$staging"
    exit "$status"
}
trap restore_exit EXIT
# Recheck after stopping: the bot could have migrated since initial validation.
python3 ops/validate_state.py "$staging" --same-format-as wg_data_alpha.json
# Preserve the original before promotion, including when it is malformed.
backup=$(mktemp /usr/bots/wg_cop/wg_data_alpha.json.pre-restore.XXXXXXXX)
cp -p wg_data_alpha.json "$backup"
mv "$staging" wg_data_alpha.json
promoted=1
systemctl start wg_cop
sleep 5
if ! systemctl is-active --quiet wg_cop; then
    echo "Restored file failed startup. Original retained at $backup; inspect service before recovery." >&2
    exit 1
fi
echo "Restore complete; original retained at $backup"
REMOTE
    ;;

  help|*)
    grep "^#" "$0" | sed 's/^# \{0,1\}//'
    echo ""
    echo "Usage: $0 {status|logs|restart|data|push-data <file>}"
    ;;

esac
